describe("write containment — the path checked is the path written", () => {
  /**
   * `resolve()` collapses `..` textually; the kernel applies it AFTER following
   * a link. `root/link/../real` is `root/real` to the first and `base/real` to
   * the second, so a check that normalises and a syscall that does not inspect
   * two different directories. Normalising at entry makes the write land where
   * the path text names it, which is the side the check already reads.
   */
  async function seedLexicalDivergence(): Promise<{ root: string; base: string }> {
    const { root, outside } = await seed();
    const base = getTempDir().dir;
    await symlink(outside, join(root, "link"), "dir");
    await mkdir(join(root, "real"), { recursive: true });
    await mkdir(join(base, "real"), { recursive: true });
    return { root, base };
  }

  it("lands the unlocked entry point on the lexical `..` target, not the kernel's", async () => {
    const { root, base } = await seedLexicalDivergence();

    await atomicWriteFileUnlocked(spell(root, "link", "..", "real", "stamity-evil.md"), "PAYLOAD\n");

    await expect(readFile(join(root, "real", "stamity-evil.md"), "utf8")).resolves.toBe("PAYLOAD\n");
    expect(await readdir(join(base, "real"))).toEqual([]);
  });

  it("normalises the locked entry point the same way", async () => {
    const { root, base } = await seedLexicalDivergence();

    await atomicWriteFile(spell(root, "link", "..", "real", "stamity-evil.md"), "PAYLOAD\n");

    await expect(readFile(join(root, "real", "stamity-evil.md"), "utf8")).resolves.toBe("PAYLOAD\n");
    expect(await readdir(join(base, "real"))).toEqual([]);
  });
});

