/**
 * The core emission composer and the thin-adapter seam.
 *
 * The CORE emits once: the `AGENTS.md` charter (plus nested monorepo copies
 * where a client's load model needs them), the vendor-neutral
 * `.agents/skills/` projection, the 6-intent hooks infrastructure, and the MCP
 * substrate. ADAPTERS carry only per-client
 * residue — paths, dialects, scoping transforms, client flags — expressed as
 * {@link ResiduePlanner}s this module composes with the core plan. An adapter
 * that re-derives something the core already planned is the design defect
 * this seam exists to rule out.
 *
 * Ownership is the composer's second job. Shared core rows (root charter,
 * skills tree, policy document) are CO-OWNED by every
 * selected tool — one write, one ledger row per owner — so a shared file
 * survives deselection of any single tool (`src/manifest/ledger.ts`: a path
 * leaves the emission set only when every owner stops emitting it). Per-tool
 * core rows (hook script copies, nested charter copies) stay single-owner:
 * they exist only for their tool and should be reclaimed with it.
 *
 * Single-writer per path, enforced: rows are deduplicated by path with a
 * content-equality assertion — two planners emitting different bytes for one
 * path is a refused planner defect, never a silent last-write-wins. The one
 * sanctioned exception is the shared-path REPLACEMENT contract
 * (`AdapterOutput.replacesSharedPath`): a residue row may substitute its
 * content for a shared core row — owners unioned, still one write. No shipped
 * planner produces one today (the codex appendix moved to its own
 * `AGENTS.override.md` row); the branch stays as a generic contract.
 *
 * MCP placement follows the same split: {@link CoreEmissionPlan.mcpFor}
 * exposes each tool's dialect documents for its adapter to place, and the
 * composer itself places none. The `codex-toml` dialect is excluded from that
 * generic surface entirely — `.codex/config.toml` is a COMPOSED document the
 * codex adapter alone renders (MCP tables plus adapter tables), and handing
 * out a standalone MCP rendering of the same path would invite a double write.
 * The file itself is owned table by table: the engine's tables are merged
 * beside the owner's (`../manifest/codexConfigToml.ts`).
 *
 * The context and planner types here are engine-side structural twins of the
 * CLI layer's `EmissionContext`/`EmissionPlanner` (`src/cli/engine/emission.ts`):
 * the import-graph gate forbids engine modules importing the CLI layer, so
 * the shapes are restated — the CLI context satisfies this one by
 * construction, and a composed planner is assignable where the CLI seam
 * expects its own interface.
 *
 * Installed packs are the composer's third job (the live-emission invariant).
 * The context resolves them from `rootDir` + the manifest ledger
 * (`src/pack/projection.ts`): pack skills join the one `.agents/skills/`
 * projection, pack agents/rules/commands flow through the SAME per-tool
 * residue planners as corpus content — the composer hands residues a derived
 * context whose content roots include the installed packs and whose selection
 * admits their artifacts — and pack hook definitions join the wired user-hook
 * lane, so every class a pack may ship has a consuming path here. Projected
 * copies are ordinary adapter-owned rows, regenerated by sync and reclaimed
 * when the pack goes; the pack's own bytes under `.stamity/packs/` are never
 * planned (install-once).
 *
 * Planning is pure with respect to the working tree: corpus, pack, and
 * user-hook reads are reads of context; nothing here writes. Two plans over
 * identical input are byte-identical — stable path ordering, no clock, no
 * randomness.
 */

