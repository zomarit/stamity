/**
 * Everything a planner may read. The CLI layer's `EmissionContext` is
 * assignable to this shape unchanged; `contentRoot` is the extra optional
 * test seam production callers never pass (the bundled corpus resolves).
 */
export interface EmissionContext {
  /** Absolute repository root the outputs will be written under. */
  rootDir: string;
  /** The manifest driving selection — tools, content selection, dials. */
  manifest: SetupManifest;
  /** Engine version, for generator stamps inside emitted content and the pinned CLI call. */
  engineVersion: string;
  /**
   * The npm package the pinned CLI call names (`${STAMITY:CLI}` renders
   * `npx -y <packageName>@<engineVersion>`). Absent means the canonical
   * `@zomarit/stamity` (`DEFAULT_CLI_PACKAGE_NAME`); a fork that renamed its
   * package passes its own name so the rendered call runs the fork.
   */
  packageName?: string;
  /**
   * Whether that package has an npm channel. Absent means it does, and the
   * call renders `npx -y`; `false` — a fork that never publishes (private, no
   * `publishConfig.registry`) — renders `npx --no`, which runs a copy already
   * installed in the project and refuses to fetch one (`../shared/cliCall.ts`).
   */
  npmChannel?: boolean;
  /**
   * The registry that serves that package's scope — a `--registry` fork's
   * `publishConfig.registry` — which every pinned call names ahead of the spec
   * (`--@<scope>:registry=<url>`). Absent: the call names none.
   */
  npmRegistry?: string;
  /** Live per-run detection decisions. */
  facts: {
    /** Live monorepo package layout; empty for single-package repos. */
    monorepoPackages: readonly PackageEntry[];
    /**
     * Where the generated hook scripts live from the client's point of view;
     * absent means `HOOKS_GENERATED_DIR/<tool>`.
     */
    hookScriptsRoot?: string;
  };
  /**
   * Corpus root override; defaults to the package-bundled corpus. External
   * callers pass a string (or nothing — the CLI seam does not carry the
   * field at all); the widened {@link ContentRoots} form is the composer's
   * internal conduit, carrying installed-pack roots into the context residue
   * planners hand straight to `buildContentIndex`.
   */
  contentRoot?: string | ContentRoots;
}

/** Plans the files a run should emit. Implementations must not touch the filesystem. */
export interface EmissionPlanner {
  /** Stable identifier, for diagnostics only — callers never branch on it. */
  readonly id: string;
  /**
   * The rows alone: the narrow view, for callers with no reporting surface —
   * an adapter suite asserting what a residue emits, the pack-projection path
   * asking which files a pack lands. Implementations here define it as
   * `(await planWithWarnings(ctx)).outputs`, so the two views cannot disagree
   * about what a run emits and a caller cannot get rows from a different pass
   * than the findings it holds.
   */
  plan(ctx: EmissionContext): Promise<AdapterOutput[]>;
  /**
   * The whole planning result — rows plus what the pass found (see
   * {@link EmissionPlan}). Every consumer with a screen takes THIS one: `init`
   * and `sync` do, because the rows alone cannot express a hook that was
   * rejected and therefore has no row.
   */
  planWithWarnings(ctx: EmissionContext): Promise<EmissionPlan>;
}

// ── Core plan ────────────────────────────────────────────────────

/** The once-emitted core output every residue planner composes against. */
export interface CoreEmissionPlan {
  /** Root charter render plus per-tool nested monorepo targets. */
  agentsMd: AgentsMdPlan;
  /** The `.agents/skills/` projection, sorted by path. */
  skills: ProjectedFile[];
  /**
   * Per tool, the rule ids that tool does NOT carry as always-on rule text
   * because the delivery option moved them into {@link skills} — empty for
   * every tool under `ruleDelivery: "always-on"` (the default) and for every
   * tool the manifest does not select.
   *
   * Computed once here rather than per adapter, because the projection and the
   * adapters have to agree exactly: a rule an adapter skips but the projection
   * did not render is delivered nowhere, and one rendered but not skipped is
   * delivered twice (see `../content/ruleDelivery.ts`).
   */
  demotedRules: Readonly<Record<Tool, ReadonlySet<string>>>;
  /** Hook scripts, the shared policy document, and per-tool interchange rows. */
  hooks: CoreHooksPlan;
  /**
   * The MCP documents `tool`'s adapter places, in the tool's dialect order —
   * empty when the manifest selects no servers. `codex` always answers empty:
   * the `codex-toml` dialect is reserved for the codex residue composer,
   * which renders the engine's tables of `.codex/config.toml`, a file owned
   * table by table (see the module header).
   */
  mcpFor(tool: Tool): McpEmission[];
  /**
   * Every MCP server the installed packs supply, sorted by id — the same rows
   * {@link mcpFor} resolves against, exposed for the ONE adapter that renders
   * its own MCP tables (codex composes the engine's tables of `.codex/config.toml`). Any
   * other consumer takes {@link mcpFor}; this field is not a second selection
   * surface, and what a repo emits is still `manifest.mcp.servers`.
   */
  packMcpServers: readonly PackSuppliedServer[];
}

