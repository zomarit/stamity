/**
 * Typed per-client capability declaration — the dialect facts an adapter
 * asserts about its platform, rendered into the generated capability matrix.
 * Every platform claim traces to a citation with an access date.
 */
export interface AdapterDialectFacts {
  tool: Tool;
  /** How the client scopes rules (e.g. `.mdc` globs, applyTo, nested files). */
  ruleShape: string;
  /**
   * Where hook config lands, or null when the client takes none v1. The hook
   * FAIL MODE (blocking vs advisory) is deliberately not restated here — its
   * source is `CLIENT_HOOK_GUARANTEES` (`src/hooks/model.ts`), which the
   * generated capability matrix renders alongside these facts.
   */
  hooksConfigPath: string | null;
  /** Whether the client reads the vendor-neutral `.agents/skills/` tree. */
  readsAgentsSkillsDir: boolean;
  /** The client's agent-definition format. */
  agentsFormat: string;
  /** The MCP config dialect the client consumes. */
  mcpDialect: McpDialect;
  /** Client entry file the adapter emits, or null when `AGENTS.md` is native. */
  entryFile: string | null;
  /** Named capability limits (budgets, caps), as declared value strings. */
  caps: { name: string; value: string }[];
  /** Platform citations backing the facts above. */
  citations: { url: string; accessDate: string }[];
}

/**
 * One tool's residue: the per-client rows the core does not own. Planners are
 * pure (no writes) and return rows already carrying ledger attribution; the
 * composer merges them with the core rows under the single-writer rules.
 */
/**
 * What one adapter's residue pass produced: its rows, and the findings no row
 * can carry.
 *
 * The second half is the reason this is an object rather than the array it used
 * to be. An adapter's most consequential per-client facts are precisely the
 * ones with no output to hang on — content the client's budget forced OUT of a
 * file, a shared path this client's emission replaced for every other selected
 * client — and the seam returned rows alone, so each was computed on every run
 * and discarded here. The core pass already had the channel
 * (`./hooksInfra.ts` → `CoreHooksPlan.warnings`, rendered by the init panel and
 * the sync report); this is the same channel, opened to the residue lane.
 */
export interface ResidueEmission {
  /** Rows this adapter owns. */
  outputs: AdapterOutput[];
  /**
   * Per-client disclosures, each already naming its own tool — the composer
   * merges them in canonical tool order and never re-labels them.
   */
  warnings?: readonly string[];
}

export interface ResiduePlanner {
  tool: Tool;
  facts: AdapterDialectFacts;
  planResidue(core: CoreEmissionPlan, ctx: EmissionContext): Promise<ResidueEmission>;
}

