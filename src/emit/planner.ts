/** `stamity-session-start.mjs` → `stamity-session-start`: the script's ledger id. */
function hookScriptArtifactId(path: string): string {
  const base = path.slice(path.lastIndexOf("/") + 1);
  const dot = base.lastIndexOf(".");
  return dot > 0 ? base.slice(0, dot) : base;
}

